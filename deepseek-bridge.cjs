// Main API endpoint
app.post('/api/claude-code', async (req, res) => {
  const { action, context, provider = 'auto', model = 'deepseek-coder' } = req.body;
  
  try {
    console.log(`Received ${action} request with provider: ${provider}, model: ${model}`);
    
    // Auto-detect best provider
    let useProvider = provider;
    if (provider === 'auto') {
      const claudeAvailable = await checkClaudeCodeCLI();
      useProvider = claudeAvailable ? 'claude' : 'deepseek';
    }
    
    console.log(`Using provider: ${useProvider}`);
    
    // Route to appropriate provider
    if (useProvider === 'deepseek') {
      const result = await handleDeepSeekRequest(action, context, model);
      res.json({
        ...result,
        _provider: 'deepseek',
        _model: model,
        _message: `Response generated by DeepSeek AI (${model})`
      });
    } else if (useProvider === 'claude') {
      const result = await handleClaudeRequest(action, context);
      res.json({
        ...result,
        _provider: 'claude',
        _model: 'claude-code-cli',
        _message: 'Response generated by Claude Code CLI'
      });
    } else {
      // Fallback to mock
      const result = await handleMockRequest(action, context);
      res.json({
        ...result,
        _provider: 'mock',
        _message: 'Mock response - no AI providers available'
      });
    }
    
  } catch (err) {
    console.error('Bridge error:', err);
    res.status(500).json({ 
      error: err.message,
      _provider: 'error',
      _fallback: 'Consider checking API keys or network connectivity'
    });
  }
});

// DeepSeek request handler
async function handleDeepSeekRequest(action, context, model) {
  switch (action) {
    case 'chat':
      const chatMessages = [
        { 
          role: 'system', 
          content: 'You are an expert software development assistant. Help with coding, debugging, and development questions. Be concise and practical.' 
        },
        { role: 'user', content: context.prompt || 'Hello' }
      ];
      
      if (context.plan) {
        chatMessages.splice(1, 0, {
          role: 'user',
          content: `Project context: ${context.plan.projectName} - ${context.plan.description}`
        });
      }
      
      const chatResponse = await callDeepSeek(chatMessages, model);
      return { response: chatResponse };

    case 'analyze':
      const analysisMessages = [
        {
          role: 'system',
          content: 'You are a senior software architect. Analyze the codebase and provide insights about architecture, code quality, and improvement suggestions.'
        },
        {
          role: 'user',
          content: `Analyze this project: ${context.plan?.projectName || 'Unknown'}\nDescription: ${context.plan?.description || 'No description'}\nFiles: ${context.files?.length || 0} files`
        }
      ];
      
      const analysisResponse = await callDeepSeek(analysisMessages, 'deepseek-r1');
      return { analysis: analysisResponse };

    case 'generate':
      const generateMessages = [
        {
          role: 'system',
          content: 'You are an expert software developer. Generate clean, production-ready code for the specified file. Only return the code, no explanations.'
        },
        {
          role: 'user',
          content: `Generate code for file: ${context.currentFile?.path || 'unknown'}\nProject: ${context.plan?.projectName}\nTech Stack: ${JSON.stringify(context.plan?.techStack)}`
        }
      ];
      
      const generateResponse = await callDeepSeek(generateMessages, 'deepseek-coder');
      return { code: generateResponse, planModificationRequest: null };

    case 'debug':
      const debugMessages = [
        {
          role: 'system',
          content: 'You are a debugging expert. Analyze the code and error, then provide the fixed code. Only return the corrected code.'
        },
        {
          role: 'user',
          content: `Debug this code:\n\nCode:\n${context.currentFile?.code}\n\nError:\n${context.prompt}`
        }
      ];
      
      const debugResponse = await callDeepSeek(debugMessages, 'deepseek-coder');
      return { fixedCode: debugResponse };

    case 'refactor':
      const refactorMessages = [
        {
          role: 'system',
          content: 'You are a refactoring expert. Analyze the codebase and suggest improvements. Respond in JSON format with "reasoning" and "filesToUpdate" fields.'
        },
        {
          role: 'user',
          content: `Analyze and suggest refactoring for this codebase with ${context.files?.length || 0} files.`
        }
      ];
      
      const refactorResponse = await callDeepSeek(refactorMessages, 'deepseek-r1');
      try {
        const parsed = JSON.parse(refactorResponse);
        return parsed;
      } catch {
        return { reasoning: refactorResponse, filesToUpdate: [] };
      }

    default:
      throw new Error(`Unknown action: ${action}`);
  }
}

// Claude request handler (existing logic)
async function handleClaudeRequest(action, context) {
  let prompt = '';
  
  switch (action) {
    case 'analyze':
      prompt = `Analyze this codebase and provide insights:\n\nProject: ${context.plan?.projectName}\nDescription: ${context.plan?.description}\n\nFiles: ${context.files?.length || 0} total files`;
      break;
    case 'generate':
      prompt = `Generate code for file: ${context.currentFile?.path}\n\nProject: ${context.plan?.projectName}\nTech Stack: ${JSON.stringify(context.plan?.techStack)}\n\nContext: This is part of a ${context.plan?.description}`;
      break;
    case 'refactor':
      prompt = `Analyze and suggest refactoring for this codebase with ${context.files?.length || 0} files. Look for code duplication, poor patterns, and improvement opportunities.`;
      break;
    case 'debug':
      prompt = `Debug this code: ${context.currentFile?.code}\n\nError: ${context.prompt}`;
      break;
    case 'chat':
      prompt = context.prompt || 'Hello';
      if (context.plan) {
        prompt += `\n\nProject context: ${context.plan.projectName} - ${context.plan.description}`;
      }
      break;
    default:
      throw new Error(`Unknown action: ${action}`);
  }
  
  return new Promise((resolve, reject) => {
    const claudeProcess = spawn('node', ['node_modules/@anthropic-ai/claude-code/cli.js', '--print', prompt], {
      stdio: ['pipe', 'pipe', 'pipe']
    });
    
    let output = '';
    let error = '';
    
    const timeout = setTimeout(() => {
      claudeProcess.kill();
      reject(new Error('Claude Code execution timed out'));
    }, 30000);
    
    claudeProcess.stdout.on('data', (data) => {
      output += data.toString();
    });
    
    claudeProcess.stderr.on('data', (data) => {
      error += data.toString();
    });
    
    claudeProcess.on('close', (code) => {
      clearTimeout(timeout);
      
      if (code === 0) {
        let result;
        switch (action) {
          case 'analyze': result = { analysis: output.trim() }; break;
          case 'generate': result = { code: output.trim(), planModificationRequest: null }; break;
          case 'refactor': 
            try { result = JSON.parse(output.trim()); } 
            catch { result = { reasoning: output.trim(), filesToUpdate: [] }; } 
            break;
          case 'debug': result = { fixedCode: output.trim() }; break;
          case 'chat': result = { response: output.trim() }; break;
        }
        resolve(result);
      } else {
        reject(new Error(error || 'Claude Code execution failed'));
      }
    });
    
    claudeProcess.on('error', (err) => {
      clearTimeout(timeout);
      reject(new Error('Failed to execute Claude Code CLI'));
    });
  });
}

